import os from 'node:os';
import path from 'node:path';
import { sha1 } from './util.mjs';

// 把 SDK getSessionMessages() 读出的对话整理成手机页面直接渲染的条目。
// 条目种类：user / assistant / thinking / tool / command / notice

const RESULT_PREVIEW = 3000;
const CODE_PREVIEW = 4000;
const TEXT_LIMIT = 200000;
const HOME = os.homedir();

// 对话里的图片（base64）放进内存，页面用 /api/blob/<hash> 取；按总大小淘汰最久没用的。
export class BlobStore {
  constructor(limitBytes = 160 * 1024 * 1024) {
    this.limit = limitBytes;
    this.size = 0;
    this.blobs = new Map();
    this.keys = new Map();
  }

  put(key, mime, base64) {
    let hash = this.keys.get(key);
    if (!hash) {
      hash = sha1(base64);
      this.keys.set(key, hash);
      if (this.keys.size > 20000) this.keys.delete(this.keys.keys().next().value);
    }
    const hit = this.blobs.get(hash);
    if (hit) {
      this.blobs.delete(hash);
      this.blobs.set(hash, hit);
      return hash;
    }
    const buf = Buffer.from(base64, 'base64');
    this.blobs.set(hash, { mime, buf });
    this.size += buf.length;
    while (this.size > this.limit && this.blobs.size > 1) {
      const [k, v] = this.blobs.entries().next().value;
      this.blobs.delete(k);
      this.size -= v.buf.length;
    }
    return hash;
  }

  get(hash) {
    return this.blobs.get(hash);
  }
}

export function stripAnsi(s) {
  return String(s).replace(/\x1b\[[0-9;?]*[ -/]*[@-~]/g, '');
}

function clip(s, n = TEXT_LIMIT) {
  s = String(s ?? '');
  return s.length > n ? `${s.slice(0, n)}\n…（内容过长，已截断）` : s;
}

function firstLine(s, n = 120) {
  const line = String(s ?? '').trim().split('\n')[0];
  return line.length > n ? `${line.slice(0, n)}…` : line;
}

function stripReminders(s) {
  return String(s ?? '').replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '');
}

export function displayPath(p, cwd) {
  if (typeof p !== 'string' || !p) return '';
  if (cwd && cwd !== '/' && (p === cwd || p.startsWith(`${cwd}/`))) return path.relative(cwd, p) || '.';
  return p.startsWith(`${HOME}/`) || p === HOME ? `~${p.slice(HOME.length)}` : p;
}

function imageRef(block, blobs, key) {
  const src = block?.source;
  if (src?.type === 'base64' && typeof src.data === 'string' && blobs) {
    return { src: `/api/blob/${blobs.put(key, src.media_type || 'image/png', src.data)}`, mime: src.media_type || 'image/png' };
  }
  if (src?.type === 'url' && /^https?:\/\//.test(src.url || '')) return { src: src.url, external: true };
  return null;
}

// 手机发附件时，消息末尾会附一段文件路径说明（方便 Claude 读取原文件）；显示时拆成附件卡片。
export const ATTACH_HEAD = '[手机附件，已保存在这台 Mac 上]';

function splitAttachments(text) {
  const i = text.indexOf(ATTACH_HEAD);
  if (i < 0) return { text, files: null };
  const files = [];
  for (const line of text.slice(i + ATTACH_HEAD.length).split('\n')) {
    const m = /^- (图片|文件) (.+?)：(\/.+)$/.exec(line.trim());
    if (!m || m[1] === '图片') continue;
    const id = /\/uploads\/([a-f0-9]{24})\//.exec(m[3])?.[1];
    files.push({ name: m[2], url: id ? `/api/upload/${id}` : null });
  }
  return { text: text.slice(0, i).trimEnd(), files: files.length ? files : null };
}

const STATUS_LABEL = { completed: '已完成', failed: '失败', killed: '已停止', stopped: '已停止', running: '运行中' };

function classifyUser(raw, originKind) {
  const text = stripReminders(raw).trim();
  if (!text) return null;
  if (/^Caveat: The messages below were generated by the user while running local commands/.test(text)) return null;

  const cmd = /<command-name>([\s\S]*?)<\/command-name>/.exec(text);
  if (cmd) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim();
    return { kind: 'command', text: [cmd[1].trim(), args].filter(Boolean).join(' ') };
  }
  const local = /<local-command-(stdout|stderr)>([\s\S]*?)<\/local-command-\1>/.exec(text);
  if (local) {
    const t = stripAnsi(local[2]).trim();
    return t ? { kind: 'notice', text: clip(t, 4000) } : null;
  }
  const bash = /<bash-input>([\s\S]*?)<\/bash-input>/.exec(text);
  if (bash) return { kind: 'command', text: `! ${bash[1].trim()}` };
  const bashOut = /<bash-(stdout|stderr)>([\s\S]*?)<\/bash-\1>/.exec(text);
  if (bashOut) {
    const t = stripAnsi(bashOut[2]).trim();
    return t ? { kind: 'notice', text: clip(t, 4000), mono: true } : null;
  }
  if (originKind === 'task-notification' || text.startsWith('<task-notification>')) {
    const summary = /<summary>([\s\S]*?)<\/summary>/.exec(text)?.[1]?.trim();
    const status = /<status>([\s\S]*?)<\/status>/.exec(text)?.[1]?.trim();
    return { kind: 'notice', text: `后台任务${STATUS_LABEL[status] ? STATUS_LABEL[status] : status ? `（${status}）` : ''}${summary ? `：${summary}` : ''}` };
  }
  if (/^\[Request interrupted by user[^\]]*\]$/.test(text)) return { kind: 'notice', text: '已中断' };
  const cross = /^<cross-session-message[^>]*?from="([^"]*)"[^>]*>([\s\S]*?)<\/cross-session-message>$/.exec(text);
  if (cross) return { kind: 'notice', text: `来自「${cross[1]}」的消息：${cross[2].trim()}`, collapsed: true };
  if (originKind && originKind !== 'human') return { kind: 'notice', text: clip(text, 4000), collapsed: true };
  const { text: body, files } = splitAttachments(text);
  return files ? { kind: 'user', text: clip(body), files } : { kind: 'user', text: clip(body) };
}

function jsonPreview(value, n = CODE_PREVIEW) {
  let s;
  try { s = JSON.stringify(value, null, 2); } catch { s = String(value); }
  return s && s.length > n ? `${s.slice(0, n)}\n…` : s;
}

function questionsOf(input) {
  return (Array.isArray(input?.questions) ? input.questions : []).map(q => ({
    question: String(q.question ?? ''),
    header: String(q.header ?? ''),
    multiSelect: !!q.multiSelect,
    options: (Array.isArray(q.options) ? q.options : []).map(o => ({ label: String(o.label ?? ''), description: String(o.description ?? '') })),
  }));
}

// 给每种工具一个简短的中文标签和一句摘要；展开后再看命令、差异和输出。
export function describeTool(name, input, cwd) {
  const i = input && typeof input === 'object' ? input : {};
  switch (name) {
    case 'Bash':
    case 'PowerShell':
      return { label: '命令', summary: i.description || firstLine(i.command), code: clip(i.command, CODE_PREVIEW), lang: 'bash' };
    case 'Read':
      return { label: '读取', summary: displayPath(i.file_path, cwd) + (i.offset ? ` · 第 ${i.offset} 行起` : '') };
    case 'Write':
      return { label: '写入', summary: displayPath(i.file_path, cwd), code: clip(i.content, CODE_PREVIEW) };
    case 'Edit':
      return { label: '编辑', summary: displayPath(i.file_path, cwd), diff: { old: clip(i.old_string, CODE_PREVIEW), new: clip(i.new_string, CODE_PREVIEW) } };
    case 'MultiEdit': {
      const edits = Array.isArray(i.edits) ? i.edits : [];
      return { label: '编辑', summary: `${displayPath(i.file_path, cwd)} · ${edits.length} 处`, diff: edits[0] ? { old: clip(edits[0].old_string, CODE_PREVIEW), new: clip(edits[0].new_string, CODE_PREVIEW) } : undefined };
    }
    case 'NotebookEdit':
      return { label: '编辑笔记本', summary: displayPath(i.notebook_path, cwd) };
    case 'Glob':
      return { label: '查找文件', summary: [i.pattern, i.path && displayPath(i.path, cwd)].filter(Boolean).join(' · ') };
    case 'Grep':
      return { label: '搜索内容', summary: [i.pattern, i.path && displayPath(i.path, cwd), i.glob].filter(Boolean).join(' · ') };
    case 'WebFetch':
      return { label: '打开网页', summary: i.url || '' };
    case 'WebSearch':
      return { label: '网页搜索', summary: i.query || '' };
    case 'Agent':
    case 'Task':
      return { label: '子任务', summary: i.description || firstLine(i.prompt), detail: i.subagent_type || undefined };
    case 'TodoWrite':
      return { label: '任务清单', summary: `${(i.todos || []).filter(t => t.status === 'completed').length}/${(i.todos || []).length} 完成`, todos: (i.todos || []).map(t => ({ text: t.content, status: t.status })) };
    case 'AskUserQuestion':
      return { label: '提问', summary: firstLine(i.questions?.[0]?.question), questions: questionsOf(i) };
    case 'ExitPlanMode':
      return { label: '计划', summary: '提交计划等待确认', plan: clip(i.plan, 20000) };
    case 'EnterPlanMode':
      return { label: '计划', summary: '进入计划模式' };
    case 'Skill':
      return { label: '技能', summary: i.skill || i.name || '' };
    case 'ToolSearch':
      return { label: '加载工具', summary: i.query || '' };
    case 'TaskOutput':
    case 'TaskStop':
    case 'BashOutput':
    case 'KillShell':
      return { label: '后台任务', summary: i.task_id || i.bash_id || i.shell_id || '' };
    case 'mcp__ccd_turn__update_plan':
      if (Array.isArray(i.items)) return { label: '计划', summary: `${i.items.filter(t => t.status === 'completed').length}/${i.items.length} 完成`, todos: i.items.map(t => ({ text: t.content, status: t.status })) };
      return { label: '计划', summary: '更新进度', hidden: true };
    case 'mcp__ccd_turn__wrap_up':
      return { label: '小结', summary: firstLine(i.recap), note: [i.recap, i.ask].filter(Boolean).join('\n\n') };
    default:
      break;
  }
  const mcp = /^mcp__(.+?)__(.+)$/.exec(name || '');
  if (mcp) {
    const server = mcp[1];
    const label = server === 'computer-use' ? '操作电脑' : server.startsWith('ccd_') ? '桌面 App' : server === 'Claude_Browser' ? '浏览器' : `MCP · ${server}`;
    return { label, summary: mcp[2].replace(/_/g, ' '), code: jsonPreview(i) };
  }
  return { label: name || '工具', summary: '', code: jsonPreview(i) };
}

function applyToolResult(item, block, outputs, blobs, key) {
  if (!item) return;
  item.status = block.is_error ? 'error' : 'done';
  const parts = typeof block.content === 'string' ? [{ type: 'text', text: block.content }] : Array.isArray(block.content) ? block.content : [];
  const text = stripAnsi(stripReminders(parts.filter(p => p.type === 'text').map(p => p.text).join('\n'))).trimEnd();
  const images = parts.filter(p => p.type === 'image').map((p, j) => imageRef(p, blobs, `${key}:${j}`)).filter(Boolean);
  if (text) {
    outputs.set(item.toolUseId, text);
    item.resultLength = text.length;
    item.result = text.length > RESULT_PREVIEW ? text.slice(0, RESULT_PREVIEW) : text;
    item.resultTruncated = text.length > RESULT_PREVIEW;
  }
  if (images.length) item.images = images;
}

export function normalizeTranscript(messages, { cwd, blobs } = {}) {
  const items = [];
  const tools = new Map();
  const outputs = new Map();
  for (const m of messages || []) {
    if (m.parent_tool_use_id) continue;
    const ts = m.timestamp || null;
    const content = m.message?.content;
    if (m.type === 'assistant') {
      (Array.isArray(content) ? content : []).forEach((b, i) => {
        const id = `${m.uuid}:${i}`;
        if (b.type === 'text') {
          if (b.text?.trim()) items.push({ id, kind: 'assistant', ts, text: clip(b.text) });
        } else if (b.type === 'thinking') {
          if (b.thinking?.trim()) items.push({ id, kind: 'thinking', ts, text: clip(b.thinking, 40000) });
        } else if (b.type === 'tool_use' || b.type === 'server_tool_use' || b.type === 'mcp_tool_use') {
          const it = { id: b.id || id, kind: 'tool', ts, toolUseId: b.id || id, name: b.name, status: b.type === 'tool_use' ? 'pending' : 'done', ...describeTool(b.name, b.input, cwd) };
          if (it.hidden) return;
          tools.set(it.toolUseId, it);
          items.push(it);
        }
      });
    } else if (m.type === 'user') {
      const blocks = typeof content === 'string' ? [{ type: 'text', text: content }] : Array.isArray(content) ? content : [];
      const texts = [];
      const images = [];
      blocks.forEach((b, i) => {
        if (b.type === 'tool_result') applyToolResult(tools.get(b.tool_use_id), b, outputs, blobs, `${m.uuid}:${i}`);
        else if (b.type === 'text') texts.push(b.text);
        else if (b.type === 'image') {
          const img = imageRef(b, blobs, `${m.uuid}:${i}`);
          if (img) images.push(img);
        } else if (b.type === 'document') texts.push(`[文档${b.title ? `：${b.title}` : ''}]`);
      });
      if (!texts.length && !images.length) continue;
      const entry = texts.length ? classifyUser(texts.join('\n\n'), m.origin?.kind) : { kind: 'user', text: '' };
      if (!entry && !images.length) continue;
      const it = { id: m.uuid, ts, ...(entry || { kind: 'user', text: '' }) };
      if (images.length) it.images = images;
      items.push(it);
    }
  }
  return { items, outputs };
}
